    public Color colorDe(Bloque tipo)
    {
        switch(tipo)
        {
            case bloqueIf:
                return new Color(41,128,185);
            case bloqueIfElse:
                return new Color(230,126,34);
            default:
                return new Color(142,68,173);
        }
    }
