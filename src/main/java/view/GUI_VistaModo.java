    public Bloque getModoElegido()
    {
        if(tglModoSwitch.isSelected())
        {
            return Bloque.bloqueSwitch;
        }
        else if(tglModoIfElse.isSelected())
        {
            return Bloque.bloqueIfElse;
        }
        return Bloque.bloqueIf;
    }

